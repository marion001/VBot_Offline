"""Generate the standalone FAQ installation sections from the two source guides.

Run from any directory; --check verifies the committed HTML is current.
No Markdown package, network request, PHP execution or native import is needed.
"""
import argparse
import html
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[3]
GUIDES = [
    ('prebuilt', 'Cài WebRTC 2.1 và PJSIP từ file ZIP đã build', 'README_INSTALL_WEBRTC21_PJSIP_PREBUILT.md'),
    ('manual', 'Build thủ công WebRTC 2.1 và PJSIP từng bước', 'README_INSTALL_WEBRTC21_PJSIP_MANUAL.md'),
]


def inline(text):
    links = {
        'README_INSTALL_WEBRTC21_PJSIP_MANUAL.md': '#native-audio-manual',
        'README_INSTALL_WEBRTC21_PJSIP_PREBUILT.md': '#native-audio-prebuilt',
        'README_INSTALL_SHARED_MEDIA_ROUTES.md': '#shared-media-routes',
        '../vbot_aec3/vbot_audio_runtime_armhf_py39.zip': 'FAQ.php?audio_native_download=zip',
        '../vbot_aec3/vbot_audio_runtime_armhf_py39.zip.sha256': 'FAQ.php?audio_native_download=checksum',
    }
    out = []
    for token in re.split(r'(`[^`]+`|\*\*[^*]+\*\*|\[[^\]]+\]\([^)]+\))', text):
        if token.startswith('`') and token.endswith('`'):
            out.append('<code>' + html.escape(token[1:-1]) + '</code>')
        elif token.startswith('**') and token.endswith('**'):
            out.append('<strong>' + html.escape(token[2:-2]) + '</strong>')
        else:
            match = re.fullmatch(r'\[([^\]]+)\]\(([^)]+)\)', token)
            if match:
                label, target = match.groups()
                url = links.get(target, target if target.startswith(('https://', 'http://')) else None)
                out.append('<a href="' + html.escape(url, quote=True) + '">' + html.escape(label) + '</a>' if url else html.escape(label))
            else:
                out.append(html.escape(token))
    return ''.join(out)


def markdown(text):
    result, paragraph, code = [], [], []
    in_code = False
    def flush():
        if paragraph:
            result.append('<p>' + inline(' '.join(paragraph)) + '</p>')
            paragraph.clear()
    for line in text.splitlines():
        if line.startswith('```'):
            flush()
            if in_code:
                result.append('<pre class="bg-dark text-light p-3 rounded overflow-auto code-block"><code>' + html.escape('\n'.join(code)) + '</code></pre>')
                code.clear()
            in_code = not in_code
        elif in_code:
            code.append(line)
        elif not line.strip():
            flush()
        elif re.match(r'^#{1,6} ', line):
            flush()
            result.append('<h5 class="border-bottom pb-2 mt-4">' + inline(line.lstrip('#').strip()) + '</h5>')
        elif line.startswith('- '):
            flush()
            result.append('<ul class="mb-2"><li>' + inline(line[2:]) + '</li></ul>')
        else:
            paragraph.append(line)
    flush()
    if in_code:
        raise ValueError('Unclosed code block')
    return '\n'.join(result)


def render():
    sections = ['''<!-- Generated by resource/tools/audio_native/render_faq.py; edit the source README guides. -->
<div class="card accordion mb-3" id="native-audio-install">
  <div class="card-body">
    <h5 class="card-title accordion-button collapsed" type="button" data-bs-toggle="collapse" data-bs-target="#collapse_native_audio_install" aria-expanded="false" aria-controls="collapse_native_audio_install">Cài WebRTC 2.1 và PJSIP</h5>
    <div id="collapse_native_audio_install" class="accordion-collapse collapse">
      <p>Chọn một trong hai hướng dẫn bên dưới: cài thư viện từ ZIP đã build hoặc tự build từng bước trên thiết bị.</p>
      <div id="native-audio-methods">''']
    for key, title, filename in GUIDES:
        guide = (ROOT / 'resource/tools' / filename).read_text(encoding='utf-8-sig')
        body = markdown(guide)
        buttons = ('<a class="btn btn-primary btn-sm me-2 mb-2" href="FAQ.php?audio_native_download=zip">Tải ZIP thư viện</a>'
                   '<a class="btn btn-outline-primary btn-sm me-2 mb-2" href="FAQ.php?audio_native_download=checksum">Tải SHA-256</a>') if key == 'prebuilt' else ''
        sections.append(f'''<div class="card accordion mb-3" id="native-audio-{key}">
  <div class="card-body">
    <h5 class="card-title accordion-button collapsed" type="button" data-bs-toggle="collapse" data-bs-target="#collapse_native_audio_{key}" aria-expanded="false" aria-controls="collapse_native_audio_{key}">{html.escape(title)}</h5>
    <div id="collapse_native_audio_{key}" class="accordion-collapse collapse" data-bs-parent="#native-audio-methods">
      <div class="alert alert-info">Thực hiện các lệnh qua SSH trên loa. Dùng Python hệ thống, không cần venv. Thư viện cài vào <code>/home/pi/VBot_AEC3/</code>.</div>
      <p>{buttons}<a class="btn btn-outline-secondary btn-sm mb-2" href="FAQ.php?audio_native_download={key}">Tải hướng dẫn .md</a></p>
      {body}
    </div>
  </div>
</div>''')
    sections.append('      </div>\n    </div>\n  </div>\n</div>')
    shared = markdown((ROOT / 'resource/tools/README_INSTALL_SHARED_MEDIA_ROUTES.md').read_text(encoding='utf-8-sig'))
    sections.append('''<div class="card accordion mb-3" id="shared-media-routes">
  <div class="card-body">
    <h5 class="card-title accordion-button collapsed" type="button" data-bs-toggle="collapse" data-bs-target="#collapse_shared_media_routes" aria-expanded="false" aria-controls="collapse_shared_media_routes">Cài đường âm thanh chung cho loa</h5>
    <div id="collapse_shared_media_routes" class="accordion-collapse collapse">''' + shared + '''</div>
  </div>
</div>''')
    return '\n'.join(sections) + '\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    target = ROOT / 'html/includes/FAQAudioNativeSection.php'
    expected = render()
    if args.check:
        if target.read_text(encoding='utf-8-sig') != expected:
            raise SystemExit('FAQ installation sections are out of date')
        print('FAQ installation sections match source guides')
    else:
        target.write_text(expected, encoding='utf-8')
        print('Updated', target)
